using System;
using System.Collections.Generic;

namespace ArcaneOnyx.GameEventGenerator
{
    /// <summary>
    /// The generated assemblies reference every extra assembly listed in the Hermes settings, so an extra
    /// assembly must not reference the generated ones back: Unity refuses to compile assemblies that
    /// reference each other in a circle.
    /// </summary>
    public static class ExtraAssemblyReferenceRules
    {
        private static readonly string[] GeneratedAssemblies = { "Hermes.EventArgs", "Hermes.Events" };

        /// <summary>
        /// Returns the error to show for the first extra assembly the generated assemblies cannot reference,
        /// or null when they can reference all of them.
        /// </summary>
        /// <param name="readReferencesOfAssembly">Gives the names of the assemblies an assembly references.</param>
        public static string FindWhyAnExtraAssemblyCannotBeReferenced(
            IEnumerable<string> extraAssemblies,
            Func<string, IEnumerable<string>> readReferencesOfAssembly)
        {
            foreach (string extraAssembly in extraAssemblies)
            {
                if (IsGeneratedByHermes(extraAssembly))
                {
                    return $"[Hermes] '{extraAssembly}' is generated by Hermes, so the generated events cannot list it as an " +
                           "extra reference. Remove it from Extra Assembly References in the Hermes settings.";
                }

                string generatedAssemblyItReferences = FindGeneratedAssemblyReferencedBy(extraAssembly, readReferencesOfAssembly);
                if (generatedAssemblyItReferences != null)
                {
                    return $"[Hermes] '{extraAssembly}' references {generatedAssemblyItReferences} (directly or through another " +
                           "assembly), so the generated events cannot reference it back. Move the types your events carry " +
                           "into an assembly that does not use Hermes, and list that one instead.";
                }
            }

            return null;
        }

        private static string FindGeneratedAssemblyReferencedBy(
            string startingAssembly,
            Func<string, IEnumerable<string>> readReferencesOfAssembly)
        {
            var assembliesAlreadyFound = new HashSet<string> { startingAssembly };
            var assembliesToRead = new Queue<string>();
            assembliesToRead.Enqueue(startingAssembly);

            while (assembliesToRead.Count > 0)
            {
                foreach (string reference in readReferencesOfAssembly(assembliesToRead.Dequeue()))
                {
                    if (IsGeneratedByHermes(reference))
                    {
                        return reference;
                    }

                    bool isFoundForTheFirstTime = assembliesAlreadyFound.Add(reference);
                    if (isFoundForTheFirstTime)
                    {
                        assembliesToRead.Enqueue(reference);
                    }
                }
            }

            return null;
        }

        private static bool IsGeneratedByHermes(string assembly)
        {
            return Array.IndexOf(GeneratedAssemblies, assembly) >= 0;
        }
    }
}
